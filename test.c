#include <immintrin.h>

__m128i set(uint16_t v) {
    return _mm_set_epi8(
        (v & 0x8000) != 0,
        (v & 0x4000) != 0,
        (v & 0x2000) != 0,
        (v & 0x1000) != 0,
        (v & 0x0800) != 0,
        (v & 0x0400) != 0,
        (v & 0x0200) != 0,
        (v & 0x0100) != 0,
        (v & 0x0080) != 0,
        (v & 0x0040) != 0,
        (v & 0x0020) != 0,
        (v & 0x0010) != 0,
        (v & 0x0008) != 0,
        (v & 0x0004) != 0,
        (v & 0x0002) != 0,
        (v & 0x0001) != 0
    );
}

__m128i seth(uint8_t v) {
    return _mm_set_epi8(
        0,
        0,
        0,
        0,
        0,
        0,
        0,
        0,
        (v & 0x0080) != 0,
        (v & 0x0040) != 0,
        (v & 0x0020) != 0,
        (v & 0x0010) != 0,
        (v & 0x0008) != 0,
        (v & 0x0004) != 0,
        (v & 0x0002) != 0,
        (v & 0x0001) != 0
    );
}
